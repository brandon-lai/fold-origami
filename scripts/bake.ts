// Bake every authored model: run the fold engine, validate every frame, and
// write public/models/<slug>.json (FOLD 1.1 + fold:* keys) plus lib/library.ts.
import { mkdirSync, writeFileSync } from "node:fs"
import { gzipSync } from "node:zlib"
import { bake } from "../lib/fold/bake"
import { validateModel } from "../lib/fold/validate"
import { MODELS, ORDER } from "../models"
import type { ModelMeta } from "../lib/fold/types"

async function main() {
  mkdirSync("public/models", { recursive: true })
  const lib: (ModelMeta & { steps: number; kb: number })[] = []
  let failed = false
  for (const slug of ORDER) {
    const t0 = Date.now()
    const baked = bake(MODELS[slug]())
    const issues = validateModel(baked)
    const json = JSON.stringify(baked)
    const kb = Math.round(gzipSync(json).length / 1024)
    writeFileSync(`public/models/${slug}.json`, json)
    lib.push({ ...baked["fold:meta"], steps: baked["fold:steps"].length, kb })
    const status = issues.length ? `FAIL ${issues.length}` : "ok"
    console.log(`${slug.padEnd(16)} ${String(baked["fold:steps"].length).padStart(3)} steps ${String(baked["fold:faces"].length).padStart(4)} faces ${String(kb).padStart(4)} KB gz  ${Date.now() - t0}ms  ${status}`)
    for (const i of issues) console.log(`   step ${i.step + 1} ${i.kind}: ${i.detail}`)
    if (issues.length) failed = true
    if (kb > 300) {
      console.log(`   over the 300 KB budget`)
      failed = true
    }
  }
  writeFileSync(
    "lib/library.ts",
    `// Generated by scripts/bake.ts. Do not edit.\nimport type { ModelMeta } from "./fold/types"\n\nexport type LibraryEntry = ModelMeta & { steps: number; kb: number }\n\nexport const LIBRARY: LibraryEntry[] = ${JSON.stringify(lib, null, 2)}\n`
  )
  if (failed) process.exit(1)
}
main().catch((e) => {
  console.error(e)
  process.exit(1)
})
